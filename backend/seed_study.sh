#!/usr/bin/env bash
# =============================================================================
# seed_study.sh — turn a study JSON into a ready-to-run seed_study() call
# =============================================================================
#
#   bash seed_study.sh [study.json] [keys-dir]
#
# Reads the study definition (copy study.example.json and edit it) plus the PI
# public key from <keys-dir>/pi_public.pem (made by keygen.sh), and writes
# _generated_seed_study.sql calling the validating seed_study() function
# (apply seed_study.sql once first).
#
# If $DATABASE_URL is set and psql is installed, the generated SQL is executed
# directly; otherwise paste the file into the Supabase SQL editor. Validation
# happens server-side either way — a bad definition produces one error listing
# every problem, and nothing is applied.
# =============================================================================
set -euo pipefail

SPEC="${1:-study.json}"
KEYS="${2:-./keys}"
OUT="_generated_seed_study.sql"

[ -f "$SPEC" ] || { echo "ERROR: $SPEC not found — copy study.example.json to $SPEC and edit it." >&2; exit 1; }
PEM_FILE="$KEYS/pi_public.pem"
[ -f "$PEM_FILE" ] || { echo "ERROR: $PEM_FILE not found — run 'bash keygen.sh $KEYS' first." >&2; exit 1; }

# Best-effort local JSON syntax check (server still validates everything).
if command -v python >/dev/null 2>&1; then
  python -c "import json,sys; json.load(open(sys.argv[1]))" "$SPEC" \
    || { echo "ERROR: $SPEC is not valid JSON (see message above)." >&2; exit 1; }
elif command -v jq >/dev/null 2>&1; then
  jq empty "$SPEC" || { echo "ERROR: $SPEC is not valid JSON." >&2; exit 1; }
fi

# Dollar-quoted so neither the JSON nor the PEM needs any escaping.
{
  echo "-- Generated by seed_study.sh from $SPEC — do not edit; edit the JSON and re-run."
  echo "select public.seed_study("
  echo "\$study_spec\$"
  cat "$SPEC"
  echo "\$study_spec\$::jsonb,"
  echo "\$pi_pem\$"
  cat "$PEM_FILE"
  echo "\$pi_pem\$"
  echo ");"
} > "$OUT"

echo "Wrote $OUT"

if [ -n "${DATABASE_URL:-}" ] && command -v psql >/dev/null 2>&1; then
  echo "Running against \$DATABASE_URL ..."
  psql "$DATABASE_URL" -f "$OUT"
else
  echo "Next: paste $OUT into the Supabase SQL editor and run it."
  echo "(Or set DATABASE_URL and install psql to run it from here.)"
fi
