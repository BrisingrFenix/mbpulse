-- -----------------------------------------------------------------------------
-- Backend API version — what the app checks before it talks to the backend
-- -----------------------------------------------------------------------------
-- The "API" is everything a client relies on: RPC signatures, tables, policies,
-- signed formats. Its version is one integer, bumped whenever that contract
-- changes; `compatible_since` is the oldest client API version the file still
-- serves (bumped only by a breaking change). Every SQL file stamps its own
-- part at its end, so a backend whose files were not all re-run reports the
-- oldest part — and a file never applied reports as missing.
--   1  before study definitions were tracked
--   2  consent linked to the exact definition (consent format v2)
--   3  join tickets + study end (enroll_participant(…, p_join_ticket))
--   4  device binding: one login session per participant (bind_session,
--      my_session_status, register_device_key), passphrase proof for key
--      rotation. Compatible since 3: the new parameters have defaults, and a
--      participant without a device key is accepted from any session.
-- Clients: mbpulse BackendCompatibility.CLIENT_API.
create table if not exists public.backend_components (
  component         text        primary key,
  api_version       int         not null,
  compatible_since  int         not null,
  applied_at        timestamptz not null default now()
);
alter table public.backend_components enable row level security;   -- read via backend_version()

-- Run by each SQL file at its end (admin only — revoked in rls_policies.sql).
create or replace function public.stamp_backend_component(p_component text, p_api int, p_compatible_since int)
returns void
language sql
as $$
  insert into public.backend_components (component, api_version, compatible_since)
  values (p_component, p_api, p_compatible_since)
  on conflict (component) do update set
    api_version = excluded.api_version,
    compatible_since = excluded.compatible_since,
    applied_at = now();
$$;

-- {"api": n, "compatibleSince": m, "missing": [...]} — before and after sign-in.
-- api = the lowest part (all files must be at least that new); compatibleSince
-- = the strictest part; missing = files never applied. A client speaking API
-- version c works when missing is empty and compatibleSince <= c <= api.
create or replace function public.backend_version()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  with expected(component) as (
    values ('00_schema'), ('rls_policies'), ('join_code'), ('withdraw'),
           ('seed_study'), ('questionnaires'), ('retention')
  )
  select jsonb_build_object(
    'api',             (select min(c.api_version) from backend_components c join expected e using (component)),
    'compatibleSince', (select max(c.compatible_since) from backend_components c join expected e using (component)),
    'missing',         coalesce((select jsonb_agg(e.component order by e.component) from expected e
                                  where not exists (select 1 from backend_components c
                                                     where c.component = e.component)), '[]'::jsonb)
  );
$$;

select public.stamp_backend_component('00_schema', 4, 3);
