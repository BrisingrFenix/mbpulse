-- =============================================================================
-- 00_schema.sql — base tables for the mbPulse backend
-- =============================================================================
--
-- APPLY FIRST, before rls_policies.sql / join_code.sql / withdraw.sql.
-- Idempotent (`if not exists` everywhere): safe to run on an existing project —
-- it will not touch tables that are already there.
--
-- Source of truth for the column names the app's DTOs expect
-- (SupabaseMeasurementRepository.kt, SyncWorker.kt). "StudyConfig" uses quoted
-- camelCase columns; everything else is snake_case.
-- =============================================================================

-- Study configuration -- one row per study; the consent flow renders from
-- "dataTypes": a JSON array of
--   {id, name, description, purpose, retentionDays, isEssential}
create table if not exists public."StudyConfig" (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  "studyId"        uuid not null default gen_random_uuid(),
  "studyName"      text null,
  "studyVersion"   real null,
  "dataTypes"      json null,
  "piPublicKey"    text null,   -- PEM; the app wraps a DEK copy under this key
  "isActive"       boolean not null default true,
  "joinCode"       text null,   -- LEGACY: superseded by Vault (join_code.sql); leave null
  constraint studyconfig_studyid_unique unique ("studyId")
);
-- Schema -> data-type map ({"omh:heart-rate": "heart_rate"}), set by
-- seed_study(); drives per-type retention (retention.sql). Separate column
-- because the app parses "dataTypes" strictly.
alter table public."StudyConfig" add column if not exists "schemaDataTypes" jsonb null;
-- PI-signed study definition: the exact JSON text the PI signed (setup wizard,
-- StudySigning.kt) and its SHA256withRSA signature by the PI-held study-signing
-- key. Apps pin that key and use ONLY the signed text (PI key, consent wording,
-- retention, sampling) — so whoever controls this database cannot swap them.
-- seed_study() checks the text matches the columns it sets.
alter table public."StudyConfig" add column if not exists "signedDefinition"    text null;
alter table public."StudyConfig" add column if not exists "definitionSignature" text null;
-- The setup wizard's custom-schema specs (fields, kinds, units), so an update
-- loads them back into the form. Wizard-only: apps never read it (their
-- schemas are compiled in as SchemaDefinitions), so it is not signed.
alter table public."StudyConfig" add column if not exists "customSchemas" jsonb null;
-- When the study ended (end_study(), seed_study.sql). "isActive" is only
-- whether enrolment is open; an ended study takes no new enrolments, consent
-- or records measured after this time, and apps stop collecting. Availability,
-- not integrity — not part of the signed definition. Never cleared by the tools.
alter table public."StudyConfig" add column if not exists "endedAt" timestamptz null;

-- Participants -- pseudonymous enrolment + recovery material
create table if not exists public.participants (
  id               bigint generated by default as identity primary key,
  created_at       timestamptz not null default now(),
  pseudo_id        uuid not null unique,
  study_id         uuid not null references public."StudyConfig"("studyId") on delete restrict,
  username         text null unique,   -- LEGACY plaintext, always null now (see below)
  public_key_b64   text not null,   -- DER X.509 SPKI, base64 (device RSA public key)
  wrapped_dek_b64  text not null,   -- DEK wrapped under the device key
  recovery_blob    text not null    -- passphrase-encrypted DEK (PBKDF2 + AES-GCM)
);

-- Pseudonymised recovery username: HMAC-SHA256(Vault pepper, client token),
-- where the client token is PBKDF2 of the normalised username computed on the
-- device (UsernameToken.kt). The plaintext username is never sent or stored;
-- linking a token back to a username needs the separately kept Vault secret
-- 'username_pepper' (rls_policies.sql). Back that secret up: without it no
-- account can be recovered.
alter table public.participants add column if not exists username_token text;
create unique index if not exists participants_username_token_key on public.participants (username_token);

-- Migration from plaintext usernames: they cannot be converted (the token is
-- derived on the device), and such participants also predate the key-rotation
-- key, so they could not recover anyway. Erase the plaintext so no username
-- remains in the database; they re-enrol to get a recoverable account.
alter table public.participants alter column username drop not null;
update public.participants set username = null where username is not null;

-- The participant's Supabase account (docs/design/participant-accounts.md):
-- created from the recovery credentials at enrolment; every participant RPC
-- and policy checks auth.uid() against it. Deleted with the participant on
-- withdrawal (confirm-withdrawal deletes the auth user).
alter table public.participants add column if not exists auth_user_id uuid
  references auth.users(id) on delete set null;
create unique index if not exists participants_auth_user_id_key on public.participants (auth_user_id);

-- Research staff per study (PI accounts: normal Supabase users with a real
-- email). Written by the setup wizard over its database connection; gates
-- export_study_records(). No client policies.
create table if not exists public.study_staff (
  user_id    uuid not null references auth.users(id) on delete cascade,
  study_id   uuid not null references public."StudyConfig"("studyId") on delete cascade,
  role       text not null default 'pi' check (role in ('pi')),
  created_at timestamptz not null default now(),
  primary key (user_id, study_id)
);
alter table public.study_staff enable row level security;

-- Key-rotation key per participant: HMAC-SHA256(DEK, label), derived on the
-- device at enrolment (KeyRotationAuth.kt). Proves, during account recovery,
-- that the caller decrypted the recovery blob. One-way — reveals nothing about
-- the DEK. Separate table, no anon policies: never readable through the API.
create table if not exists public.participant_rotation_keys (
  pseudo_id        uuid primary key references public.participants(pseudo_id) on delete cascade,
  rotation_key_b64 text not null
);
alter table public.participant_rotation_keys enable row level security;

-- Proof of the PASSPHRASE for key rotation: PBKDF2(passphrase, rotation label
-- + client username token), derived on the device at enrolment / recovery and
-- never stored there (ParticipantCredentials.passphraseKey). The rotation key
-- above is derived from the DEK, which every enrolled phone holds — this one
-- only whoever knows the passphrase, so an old phone cannot take the account
-- back after a recovery. Null for participants enrolled before it existed
-- until their next recovery registers it.
alter table public.participant_rotation_keys add column if not exists passphrase_key_b64 text;

-- Device binding: only ONE login session acts for a participant — the one of
-- the phone that enrolled or last recovered the account. device_key_b64 is a
-- random secret only that phone holds (sealed in its Keystore, DeviceKeyStore);
-- a new login on the same phone re-attaches with an HMAC proof of it
-- (bind_session). Recovery replaces both, so the previous phone's requests are
-- refused even after it signs in again. Null = not bound yet (enrolled before
-- binding existed): any session of the account is accepted, as before.
alter table public.participants add column if not exists device_key_b64   text;
alter table public.participants add column if not exists bound_session_id uuid;

-- One-time session-binding nonces (5 min), for the session that asked; consumed by bind_session().
create table if not exists public.session_challenges (
  pseudo_id  uuid primary key references public.participants(pseudo_id) on delete cascade,
  challenge  text        not null,
  session_id uuid        not null,
  expires_at timestamptz not null
);
alter table public.session_challenges enable row level security;

-- One-time key-rotation nonces (5 min), consumed by rotate_participant_keys().
create table if not exists public.key_rotation_challenges (
  pseudo_id  uuid primary key references public.participants(pseudo_id) on delete cascade,
  challenge  text        not null,
  expires_at timestamptz not null
);
alter table public.key_rotation_challenges enable row level security;

-- Consent records -- append-only audit of per-type decisions
create table if not exists public.consent_records (
  id                      bigint generated by default as identity primary key,
  created_at              timestamptz not null default now(),
  participant_pseudo_id   uuid not null references public.participants(pseudo_id) on delete cascade,
  study_id                uuid not null references public."StudyConfig"("studyId") on delete restrict,
  study_version           text not null,
  completed_at_ms         bigint not null,
  decisions               json not null
);
-- Participant signature (SHA256withRSA, device key) over the canonical consent
-- string (ConsentSignature.kt) + the key that made it. Null only on records
-- written before signing existed; submit_consent_record() requires both.
alter table public.consent_records add column if not exists signature_b64         text null;
alter table public.consent_records add column if not exists signer_public_key_b64 text null;

-- Every study definition ever applied, append-only (seed_study() adds one per
-- definition; rls_policies.sql makes them immutable): the exact text the PI
-- signed — or, for an unsigned (development) study, seed_study()'s canonical
-- JSON of it — keyed by its SHA-256 (hex of the UTF-8 bytes). A consent record
-- names the definition it was given for (consent_records.definition_sha256,
-- also inside the participant's signature), so the terms each participant
-- agreed to stay retrievable after the study is updated.
create table if not exists public.study_definitions (
  definition_sha256     text        primary key,
  study_id              uuid        not null references public."StudyConfig"("studyId") on delete restrict,
  study_version         text        not null,
  definition            text        not null,
  definition_signature  text        null,      -- PI signature (base64); null = unsigned study
  issued_at             timestamptz null,      -- signed definitions: their "issuedAt"
  published_at          timestamptz not null default now()
);
create index if not exists idx_study_definitions_study on public.study_definitions (study_id, published_at);
-- The study's current definition (set by seed_study()).
alter table public."StudyConfig" add column if not exists "definitionSha256" text null;
-- The definition a consent record was given for. Null only for records made
-- before definitions were tracked (consent format v1 — linked by version label only).
alter table public.consent_records add column if not exists definition_sha256 text null
  references public.study_definitions (definition_sha256) on delete restrict;

-- Encrypted health records -- E2E ciphertext; the server never sees plaintext
create table if not exists public.encrypted_records (
  id                          bigint generated by default as identity primary key,
  created_at                  timestamptz not null default now(),
  participant_pseudo_id       uuid not null references public.participants(pseudo_id) on delete cascade,
  study_id                    uuid not null references public."StudyConfig"("studyId") on delete restrict,
  epoch_start_ms              bigint not null,
  schema_name                 text not null,
  ciphertext_hex              text not null,   -- IV || AES-256-GCM ciphertext, hex
  participant_wrapped_dek_hex text not null,
  pi_wrapped_dek_hex          text not null,
  constraint encrypted_records_unique_epoch
    unique (participant_pseudo_id, epoch_start_ms, schema_name)
);

-- Data export log -- powers the "your data was accessed" transparency banner
create table if not exists public.data_exports (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  study_id        uuid not null references public."StudyConfig"("studyId") on delete restrict,
  exported_at_ms  bigint not null,
  record_count    int not null,
  note            text null
);

-- Paged PI exports: one data_exports row per export, then pages fetched under
-- it (the API caps a response at 1000 rows). Only export_study_records()
-- touches this table — RLS on, no policies. max_id freezes the export to the
-- records that existed when it was logged.
create table if not exists public.export_sessions (
  export_id  bigint primary key references public.data_exports(id) on delete cascade,
  user_id    uuid not null,
  study_id   uuid not null,
  max_id     bigint not null,
  expires_at timestamptz not null
);
alter table public.export_sessions enable row level security;

