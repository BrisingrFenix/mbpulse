-- =============================================================================
-- retention.sql — delete encrypted records once their retention period ends
-- =============================================================================
--
-- Apply after seed_study.sql and questionnaires.sql. Re-runnable (`if not exists` / `create or replace`).
--
-- Each consent data type in "StudyConfig"."dataTypes" has a "retentionDays"
-- (the ethics-approved period shown on the consent screen). A record is deleted
-- `retentionDays` after it was RECORDED (its measurement time), rolling.
--
-- The server only sees a record's OMH schema_name; which data type a schema
-- belongs to is the app's schemaToConsentType mapping. seed_study() stores a
-- copy of that mapping in "StudyConfig"."schemaDataTypes"
-- ({"omh:heart-rate": "heart_rate", ...}). Records whose schema is not in the
-- mapping fall back to the study's LONGEST retention period, so no record
-- outlives every approved period; the purge log counts them so the researcher
-- can fix the mapping.
--
-- Measurement time = least(epoch_start_ms, created_at): a device with a clock
-- in the future cannot extend a record's life past upload + retention.
--
-- Scheduled daily with pg_cron (built into Supabase and `supabase start`). Runs
-- as SECURITY DEFINER because anon tables are append-only; not exposed to anon.
-- =============================================================================

-- Schema -> data-type mapping, written by seed_study(). Separate column (not a
-- key inside "dataTypes") because the app parses "dataTypes" strictly.
alter table public."StudyConfig" add column if not exists "schemaDataTypes" jsonb null;

-- Append-only audit of every purge run (one row per study/data type that lost
-- records). No participant identifiers — counts only.
create table if not exists public.retention_purges (
  id               bigint generated by default as identity primary key,
  run_at           timestamptz not null default now(),
  study_id         uuid        not null
                   references public."StudyConfig" ("studyId") on delete restrict,
  data_type_id     text        null,      -- null = schema not in "schemaDataTypes"
  retention_days   int         not null,
  records_deleted  int         not null
);
alter table public.retention_purges enable row level security;
-- No anon policies: written by purge_expired_records(), read by PI tooling.

create index if not exists idx_encrypted_records_epoch
  on public.encrypted_records (study_id, schema_name, epoch_start_ms);

create or replace function public.purge_expired_records()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total int := 0;
  v_rows  jsonb := '[]'::jsonb;
  r       record;
  n       int;
begin
  -- One retention period per (study, schema): the mapped data type's, else the
  -- study's longest. Studies with no dataTypes are skipped.
  for r in
    with types as (
      select s."studyId" as study_id,
             t->>'id'    as type_id,
             (t->>'retentionDays')::int as days
      from "StudyConfig" s,
           json_array_elements(s."dataTypes") t
      where s."dataTypes" is not null
        and (t->>'retentionDays') ~ '^[0-9]+$'
    ),
    study_max as (
      select study_id, max(days) as days from types group by study_id
    ),
    schemas as (
      select distinct study_id, schema_name from encrypted_records
    )
    select sc.study_id,
           sc.schema_name,
           ty.type_id,
           coalesce(ty.days, sm.days) as days
    from schemas sc
    join study_max sm on sm.study_id = sc.study_id
    join "StudyConfig" s on s."studyId" = sc.study_id
    left join types ty
      on ty.study_id = sc.study_id
     -- Questionnaire answers ("questionnaire:<id>") belong to the data type
     -- their questionnaire names (questionnaires.sql).
     and ty.type_id  = coalesce(s."schemaDataTypes"->>sc.schema_name,
                                (select q.data_type from questionnaires q
                                  where q.study_id = sc.study_id
                                    and 'questionnaire:' || q.questionnaire_id = sc.schema_name))
  loop
    with d as (
      delete from encrypted_records e
      where e.study_id    = r.study_id
        and e.schema_name = r.schema_name
        and least(to_timestamp(e.epoch_start_ms / 1000.0), e.created_at)
            < now() - make_interval(days => r.days)
      returning 1
    ) select count(*) into n from d;

    if n > 0 then
      insert into retention_purges (study_id, data_type_id, retention_days, records_deleted)
      values (r.study_id, r.type_id, r.days, n);
      v_total := v_total + n;
      v_rows := v_rows || jsonb_build_object(
        'studyId', r.study_id, 'schema', r.schema_name,
        'dataType', r.type_id, 'retentionDays', r.days, 'deleted', n);
    end if;
  end loop;

  return jsonb_build_object('deleted', v_total, 'details', v_rows);
end;
$$;

revoke execute on function public.purge_expired_records() from public, anon, authenticated;
grant  execute on function public.purge_expired_records() to service_role;

-- -----------------------------------------------------------------------------
-- Account housekeeping (docs/design/participant-accounts.md §6.4, §8)
-- -----------------------------------------------------------------------------
-- 1. Participant accounts with no participant row after 24 h are abandoned
--    enrolments (or sign-up spam — sign-ups are open, accounts without a
--    participant can do nothing). Staff accounts (study_staff) are kept.
-- 2. The Auth audit log ties sign-ins (IP, user agent) to account ids, and
--    through them to pseudonyms — keep it only as long as needed.
create or replace function public.purge_orphan_accounts(p_audit_log_days int default 30)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_accounts int := 0;
  v_audit    int := 0;
begin
  with d as (
    delete from auth.users u
     where u.created_at < now() - interval '24 hours'
       and u.email like '%@participants.invalid'
       and not exists (select 1 from participants p where p.auth_user_id = u.id)
       and not exists (select 1 from study_staff s where s.user_id = u.id)
    returning 1
  ) select count(*) into v_accounts from d;

  if to_regclass('auth.audit_log_entries') is not null then
    begin
      execute format('with d as (delete from auth.audit_log_entries where created_at < now() - make_interval(days => %s) returning 1) select count(*) from d', p_audit_log_days)
        into v_audit;
    exception when insufficient_privilege then
      raise notice 'cannot prune auth.audit_log_entries (insufficient privilege) — set its retention in the Supabase dashboard';
    end;
  end if;

  return jsonb_build_object('orphanAccountsDeleted', v_accounts, 'auditLogEntriesDeleted', v_audit);
end;
$$;

revoke execute on function public.purge_orphan_accounts(int) from public, anon, authenticated;
grant  execute on function public.purge_orphan_accounts(int) to service_role;

-- Daily at 03:17 UTC. cron.schedule with a job name replaces an existing job of
-- that name, so re-running this file does not duplicate it. If pg_cron cannot
-- be enabled (non-Supabase Postgres without it), the purge still exists and can
-- be called by any external scheduler: select public.purge_expired_records();
do $do$
begin
  begin
    create extension if not exists pg_cron;
  exception when others then
    raise notice 'pg_cron unavailable (%): schedule purge_expired_records() externally', sqlerrm;
    return;
  end;
  perform cron.schedule(
    'purge-expired-records',
    '01 0 * * *',
    'select public.purge_expired_records()'
  );
  perform cron.schedule(
    'purge-orphan-accounts',
    '01 0 * * *',
    'select public.purge_orphan_accounts()'
  );
end
$do$;

